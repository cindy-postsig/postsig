interface MonthlyReportData {
  overview: {
    currentMonthSpend: {
      amount: number;
      label: string;
    };
    nextMonthSpend: {
      amount: number;
      change: number;
      changePercent: number;
      label: string;
    };
  };
  spendByBusinessGroup: BusinessSponsorAndGroupData[];
  spendByBusinessSponsor: BusinessSponsorAndGroupData[];
  priceChanges: PriceChangeData[];
  upcomingRenewalsContracts: any[];
  topVendorsBySpend: TopVendorData[];
  selectedTag?: string | null;
}

/**
 * Format a number as currency string for Excel. Every figure the report engine
 * produces is converted into the org's base currency before it is grouped, so
 * `currency` is that base — except the renewals sheet, which lists one contract
 * per row and passes each contract's own currency.
 */
function formatCurrencyForExcel(amount: number, currency: string): string {
  return formatCurrency(amount, currency, true) || '0';
}

/**
 * Format percentage for Excel
 */
function formatPercentage(value: number): string {
  if (value === 0) return '0%';
  const absValue = Math.abs(value);
  if (absValue >= 1) return value.toFixed(1) + '%';
  if (absValue >= 0.1) return value.toFixed(2) + '%';
  return value.toFixed(3) + '%';
}

/**
 * Create Overview worksheet
 */
function createOverviewSheet(
  workbook: ExcelJS.Workbook,
  overview: MonthlyReportData['overview'],
  baseCurrency: string,
  selectedTag?: string | null,
  viewMode: 'amortized' | 'actual' = 'amortized',
): void {
  const currentDate = format(new Date(), 'MMMM d, yyyy');
  const worksheet = workbook.addWorksheet('Overview');

  // Add title with optional tag and view mode
  const viewLabel = viewMode === 'actual' ? 'Actual Cost' : 'Amortized';
  const title = selectedTag
    ? `Monthly Budget Report (${viewLabel}) - ${selectedTag}`
    : `Monthly Budget Report (${viewLabel})`;
  const titleRow = worksheet.addRow([title]);
  titleRow.font = { bold: true };

  // Add generated date
  worksheet.addRow(['Generated by PostSig', currentDate]);

  // Empty row
  worksheet.addRow([]);

  // Add headers
  const headerRow = worksheet.addRow([
    `${viewLabel} Spend`,
    'Amount',
    'Change',
  ]);
  headerRow.font = { bold: true };

  // Add data rows
  worksheet.addRow([
    'Current Month',
    formatCurrencyForExcel(overview.currentMonthSpend.amount, baseCurrency),
    '-',
  ]);

  worksheet.addRow([
    'Next Month',
    formatCurrencyForExcel(overview.nextMonthSpend.amount, baseCurrency),
    `${formatCurrencyForExcel(overview.nextMonthSpend.change, baseCurrency)} (${formatPercentage(overview.nextMonthSpend.changePercent)})`,
  ]);

  // Set column widths
  worksheet.columns = [
    { width: 30 }, // Spend column
    { width: 20 }, // Amount
    { width: 25 }, // Change
  ];
}

/**
 * Create Spend by Business Sponsor worksheet
 */
// Every row on these sheets is one contract's slice of a sponsor/group, so it
// exports in that contract's own currency (PSK-1796). The sheets emit no rollup
// rows, so nothing here needs the base currency.
function createSpendByBusinessSponsorSheet(
  workbook: ExcelJS.Workbook,
  spendByBusinessSponsor: BusinessSponsorAndGroupData[],
  viewMode: 'amortized' | 'actual' = 'amortized',
): void {
  const worksheet = workbook.addWorksheet('Spend by Business Sponsor');
  const viewLabel = viewMode === 'actual' ? 'Actual Cost' : 'Amortized';

  // Add headers
  const headerRow = worksheet.addRow([
    'Business Sponsor',
    'Vendor',
    'Product',
    'Split Fee',
    `Current Month (${viewLabel})`,
    `Next Month (${viewLabel})`,
    'Change',
    'Tags',
  ]);
  headerRow.font = { bold: true };

  // Add data rows
  spendByBusinessSponsor.forEach((sponsor) => {
    sponsor.subRows.forEach((subRow) => {
      worksheet.addRow([
        sponsor.name, // Repeat sponsor name on each row for easy filtering
        subRow.vendor,
        subRow.product,
        subRow.isSplit ? 'Yes' : 'No',
        formatCurrencyForExcel(subRow.displayCurrentMonth, subRow.currency),
        formatCurrencyForExcel(subRow.displayNextMonth, subRow.currency),
        formatCurrencyForExcel(subRow.displayChange, subRow.currency),
        subRow.tags.join(', '),
      ]);
    });
  });

  // Set column widths
  worksheet.columns = [
    { width: 25 }, // Business Sponsor
    { width: 25 }, // Vendor
    { width: 30 }, // Product
    { width: 12 }, // Split Fee
    { width: 28 }, // Current Month
    { width: 28 }, // Next Month
    { width: 18 }, // Change
    { width: 25 }, // Tags
  ];
}

