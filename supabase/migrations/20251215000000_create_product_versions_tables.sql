-- (Primary key was changed to composite key, but we need id for version FK)
--------------------------------------------------------------------------------

CREATE UNIQUE INDEX IF NOT EXISTS vendor_products_details_id_unique
    ON public.vendor_products_details(id);

--------------------------------------------------------------------------------
-- Create vendor_products_versions table
--------------------------------------------------------------------------------

CREATE TABLE public.vendor_products_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_product_id integer NOT NULL REFERENCES public.vendor_products(id) ON DELETE CASCADE,
    contract_id integer NOT NULL REFERENCES public.contracts(id) ON DELETE CASCADE,
    contract_version_id bigint NOT NULL REFERENCES public.contract_versions(id) ON DELETE CASCADE,
    version_id bigint NOT NULL,
    valid_from timestamptz NOT NULL DEFAULT now(),
    valid_to timestamptz,
    changed_data jsonb,
    created_by uuid REFERENCES public.users(id) ON UPDATE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    actor text,
    comment text,
    organization_id uuid REFERENCES public.organizations(id) ON DELETE CASCADE,

    -- Mirrored vendor_products columns
    vendor_id integer,
    name character varying,
    delivery_method_id integer,
    updated_at timestamptz,

    CONSTRAINT vendor_products_versions_product_version_unique UNIQUE (vendor_product_id, version_id)
);

CREATE INDEX idx_vendor_products_versions_vendor_product_id ON public.vendor_products_versions(vendor_product_id);
CREATE INDEX idx_vendor_products_versions_contract_id ON public.vendor_products_versions(contract_id);
CREATE INDEX idx_vendor_products_versions_contract_version_id ON public.vendor_products_versions(contract_version_id);
CREATE INDEX idx_vendor_products_versions_organization_id ON public.vendor_products_versions(organization_id);
CREATE INDEX idx_vendor_products_versions_valid_from ON public.vendor_products_versions(valid_from);
CREATE INDEX idx_vendor_products_versions_created_by ON public.vendor_products_versions(created_by);

COMMENT ON TABLE public.vendor_products_versions IS 'Stores versioned snapshots of vendor products for edit history tracking';
COMMENT ON COLUMN public.vendor_products_versions.vendor_product_id IS 'Reference to the original vendor_product being versioned';
COMMENT ON COLUMN public.vendor_products_versions.contract_id IS 'The contract this vendor product version is associated with';
COMMENT ON COLUMN public.vendor_products_versions.contract_version_id IS 'Reference to the specific contract version this was part of';
COMMENT ON COLUMN public.vendor_products_versions.version_id IS 'Incrementing version number per vendor product (1, 2, 3, ...)';
COMMENT ON COLUMN public.vendor_products_versions.valid_from IS 'Timestamp when this version became active';
COMMENT ON COLUMN public.vendor_products_versions.valid_to IS 'Timestamp when this version was superseded (NULL if current)';
COMMENT ON COLUMN public.vendor_products_versions.changed_data IS 'JSON object tracking field changes, e.g., {"name": {"old": "Product A", "new": "Product B"}}';
COMMENT ON COLUMN public.vendor_products_versions.actor IS 'Type of actor that made the change (e.g., "user", "system", "api")';

ALTER TABLE public.vendor_products_versions ENABLE ROW LEVEL SECURITY;

