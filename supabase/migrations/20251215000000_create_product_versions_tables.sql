-- Migration: Create product version tables and fix RLS policies
-- 1. Fix contract_versions RLS to use contracts_visible_to() helper
-- 2. Add unique constraint on vendor_products_details.id for FK reference
-- 3. Create vendor_products_versions table
-- 4. Create vendor_products_details_versions table
-- 5. Create vendor_products_users_versions table

--------------------------------------------------------------------------------
-- Fix contract_versions RLS policy
--------------------------------------------------------------------------------

DROP POLICY IF EXISTS "contract_versions_read" ON public.contract_versions;

CREATE POLICY "contract_versions_read" ON public.contract_versions
    FOR SELECT
    TO authenticated
    USING (
        contract_id IN (
            SELECT id FROM contracts_visible_to(
                (SELECT organization_id FROM users WHERE id = auth.uid()),
                auth.uid()
            )
        )
    );

DROP POLICY IF EXISTS "contract_versions_anon_deny" ON public.contract_versions;

CREATE POLICY "contract_versions_anon_deny" ON public.contract_versions
    FOR ALL
    TO anon
    USING (false);

