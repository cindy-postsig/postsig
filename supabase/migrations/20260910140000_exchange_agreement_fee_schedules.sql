-- Exchange Agreement (EAPFS) fee schedule data (PSK-1920): exchanges,
-- fee_schedule_versions, fee_schedule_line_items, plus a private storage
-- bucket for the source PDFs.
--
-- Shared reference data, not org-scoped (mirrors the bloomberg_sid_*
-- tables' read-any-authenticated, write-via-service-role-only precedent) --
-- a fee schedule is the same for every org. Not linked to
-- contract_types.EAFeeSchedule; that type is for the unrelated
-- document-classification pipeline.
--
-- No insert/update/delete policies below: these tables are populated only
-- by scripts/seed-exchange-agreements.local.ts (and its future
-- non-local equivalent) via the service-role key, which bypasses RLS
-- entirely. There is no authenticated write path -- Postsig staff don't use
-- the client app to maintain this data -- so RLS's default-deny for
-- anything without a matching policy is exactly the intended behavior.

-- Restricts reads to orgs with the exchange-agreements module toggle on
-- (organization_modules.settings.exchange_agreements_enabled under the cpm
-- module) -- the same per-org admin toggle already used for CSV
-- export/MCP/invoices (set from the admin panel). Centralizes the check
-- instead of each select policy below inlining its own EXISTS subquery.
create or replace function "public"."has_exchange_agreements_access"()
returns boolean
language sql
stable
security invoker
set search_path to 'public', 'pg_temp'
as $$
    select exists (
        select 1
        from "public"."organization_modules" om
        join "public"."app_modules" am on am.id = om.module_id
        where om.organization_id = public.user_organization_id()
          and am.code = 'cpm'
          and coalesce((om.settings->>'exchange_agreements_enabled')::boolean, false)
    );
$$;

-- exchanges: lookup for the 4 exchanges the FE renders (only euronext has
-- versions/line items today; the rest use the FE's existing empty state).
create table "public"."exchanges" (
    "id" bigint generated by default as identity not null,
    "code" text not null,
    "name" text not null,
    "currency" text not null,
    "created_at" timestamptz not null default now()
);

CREATE UNIQUE INDEX "exchanges_pkey" ON "public"."exchanges" USING btree ("id");
alter table "public"."exchanges" add constraint "exchanges_pkey" PRIMARY KEY using index "exchanges_pkey";

alter table "public"."exchanges" add constraint "exchanges_code_unique" UNIQUE ("code");

comment on column "public"."exchanges"."currency" is 'Display symbol (e.g. €, £, $), not an ISO code — matches ExchangeSummary.currency in lib/exchange-agreement/types.ts.';

-- fee_schedule_versions: one row per vintage/release. version/effective_date/
-- invalidated_date/source_doc are release-wide in the source export --
-- constant across every product line and row in one vintage.
create table "public"."fee_schedule_versions" (
    "id" bigint generated by default as identity not null,
    "exchange_id" bigint not null,
    "vintage_slug" text not null,
    "version" text not null,
    "effective_date" date not null,
    "invalidated_date" date,
    "source_doc" text,
    "source_document_path" text,
    "created_at" timestamptz not null default now()
);

CREATE UNIQUE INDEX "fee_schedule_versions_pkey" ON "public"."fee_schedule_versions" USING btree ("id");
alter table "public"."fee_schedule_versions" add constraint "fee_schedule_versions_pkey" PRIMARY KEY using index "fee_schedule_versions_pkey";

comment on column "public"."fee_schedule_versions"."vintage_slug" is 'Export directory name, e.g. enx_emda_fee_schedule_01.07.2026_efd.';
comment on column "public"."fee_schedule_versions"."source_doc" is 'Original source PDF filename from the export. Populated even when the binary is not yet available.';
comment on column "public"."fee_schedule_versions"."source_document_path" is 'Storage object path in the exchange-fee-schedule-docs bucket once the PDF is uploaded. Null until then -- View Source stays disabled.';

-- Scoped to exchange, not bare-column-unique: the FE's logicalVersions()
-- merge-by-version-number depends on version numbers being unique per
-- exchange, not globally.
alter table "public"."fee_schedule_versions" add constraint "fee_schedule_versions_exchange_slug_unique" UNIQUE ("exchange_id", "vintage_slug");
alter table "public"."fee_schedule_versions" add constraint "fee_schedule_versions_exchange_version_unique" UNIQUE ("exchange_id", "version");

CREATE INDEX "idx_fee_schedule_versions_exchange_effective" ON "public"."fee_schedule_versions" USING btree ("exchange_id", "effective_date");

alter table "public"."fee_schedule_versions" add constraint "fee_schedule_versions_exchange_id_fkey" FOREIGN KEY ("exchange_id") REFERENCES "public"."exchanges"("id") not valid;
alter table "public"."fee_schedule_versions" validate constraint "fee_schedule_versions_exchange_id_fkey";

