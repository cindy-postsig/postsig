create policy "fee_schedule_versions_select" on "public"."fee_schedule_versions" for select to authenticated using (has_exchange_agreements_access());
revoke all on "public"."fee_schedule_versions" from anon;

create policy "fee_schedule_line_items_anon_deny" on "public"."fee_schedule_line_items" for all to anon using (false);
create policy "fee_schedule_line_items_select" on "public"."fee_schedule_line_items" for select to authenticated using (has_exchange_agreements_access());
revoke all on "public"."fee_schedule_line_items" from anon;

-- Private, service-role-write, shared-read bucket for source PDFs -- new
-- rather than reusing documents/contract_docs, since those are org-scoped
-- by folder path and this data is not.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
    'exchange-fee-schedule-docs',
    'exchange-fee-schedule-docs',
    false,
    52428800, -- 50MB
    array['application/pdf']
);

create policy "exchange_fee_schedule_docs_select" on storage.objects
    for select to authenticated
    using (bucket_id = 'exchange-fee-schedule-docs' and has_exchange_agreements_access());

create policy "exchange_fee_schedule_docs_anon_deny" on storage.objects
    for all to anon
    using (bucket_id = 'exchange-fee-schedule-docs' and false);
