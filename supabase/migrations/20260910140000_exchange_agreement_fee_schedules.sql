    "counterparty_role" text,
    "asset_class" text,
    "market" text,
    "venues" text,
    "level" text,
    "customer_tier" text,
    "user_class" text,
    "distribution_channel" text,
    "data_timeliness" text,
    "display_medium" text,
    "granularity" text,
    "user_count_tier" text,

    "product_code" text,
    "product_code_root" text,

    "fee_basis" text,
    "charge_subtype" text,
