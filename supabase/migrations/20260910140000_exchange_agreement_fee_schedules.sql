CREATE UNIQUE INDEX "fee_schedule_line_items_pkey" ON "public"."fee_schedule_line_items" USING btree ("id");
alter table "public"."fee_schedule_line_items" add constraint "fee_schedule_line_items_pkey" PRIMARY KEY using index "fee_schedule_line_items_pkey";

comment on column "public"."fee_schedule_line_items"."product_id" is 'Export cluster id -- stable across vintages for the same product, but NOT unique per row within one vintage (one product_id can span many distinct priced rows). Use for cross-version product tracking only, never as a per-row key.';
comment on column "public"."fee_schedule_line_items"."section_family" is 'The FE''s "product line". Blank on a large, inconsistent fraction of rows in the source export (25-45% per vintage) -- the seed script maps blanks to a placeholder value; see the EAPFS data implementation plan for the open question this represents.';
comment on column "public"."fee_schedule_line_items"."product_code" is 'Exchange Agreement Product Code (e.g. MAFFL2-TPLNDRUA). Future join key to vendor_products.product_code (see migration 20260803120000) for Service Order/Invoice matching -- not joined yet.';
comment on column "public"."fee_schedule_line_items"."page" is 'Page number in the source PDF -- provenance for deep-linking once source_document_path is populated.';

CREATE INDEX "idx_fee_schedule_line_items_version" ON "public"."fee_schedule_line_items" USING btree ("version_id");
CREATE INDEX "idx_fee_schedule_line_items_product" ON "public"."fee_schedule_line_items" USING btree ("product_id");
CREATE INDEX "idx_fee_schedule_line_items_product_code" ON "public"."fee_schedule_line_items" USING btree ("product_code") where "product_code" is not null;

alter table "public"."fee_schedule_line_items" add constraint "fee_schedule_line_items_version_id_fkey" FOREIGN KEY ("version_id") REFERENCES "public"."fee_schedule_versions"("id") ON DELETE CASCADE not valid;
alter table "public"."fee_schedule_line_items" validate constraint "fee_schedule_line_items_version_id_fkey";

-- Atomic delete+insert for one version: a client-side delete-then-N-inserts
-- isn't atomic, so a failure partway through re-seeding would leave a
-- version with partial line items indistinguishable from "never seeded".
create or replace function "public"."replace_fee_schedule_line_items"(
    p_version_id bigint,
    p_rows jsonb
)
returns void
language plpgsql
security invoker
set search_path to 'public', 'pg_temp'
as $$
begin
    delete from "public"."fee_schedule_line_items" where "version_id" = p_version_id;

    insert into "public"."fee_schedule_line_items" (
        "version_id", "product_id", "price_point_id", "vintage_price_point_id",
        "title", "section_family", "section_path", "row_label", "column_labels",
        "fee", "text_value", "currency",
        "use_type", "counterparty_role", "asset_class", "market", "venues", "level",
        "customer_tier", "user_class", "distribution_channel", "data_timeliness",
        "display_medium", "granularity", "user_count_tier",
        "product_code", "product_code_root",
        "fee_basis", "charge_subtype", "fee_basis_notes", "consolidated_pack",
        "page", "block_id"
    )
    select
        p_version_id, r.product_id, r.price_point_id, r.vintage_price_point_id,
        r.title, r.section_family, r.section_path, r.row_label, r.column_labels,
        r.fee, r.text_value, r.currency,
        r.use_type, r.counterparty_role, r.asset_class, r.market, r.venues, r.level,
        r.customer_tier, r.user_class, r.distribution_channel, r.data_timeliness,
        r.display_medium, r.granularity, r.user_count_tier,
        r.product_code, r.product_code_root,
        r.fee_basis, r.charge_subtype, r.fee_basis_notes, r.consolidated_pack,
        r.page, r.block_id
    from jsonb_to_recordset(p_rows) as r(
        product_id text, price_point_id text, vintage_price_point_id text,
        title text, section_family text, section_path text[], row_label text[], column_labels text[],
        fee numeric, text_value text, currency text,
        use_type text, counterparty_role text, asset_class text, market text, venues text, level text,
        customer_tier text, user_class text, distribution_channel text, data_timeliness text,
        display_medium text, granularity text, user_count_tier text,
        product_code text, product_code_root text,
        fee_basis text, charge_subtype text, fee_basis_notes text, consolidated_pack text,
        page int, block_id text
    );
end;
$$;

alter table "public"."exchanges" enable row level security;
alter table "public"."fee_schedule_versions" enable row level security;
alter table "public"."fee_schedule_line_items" enable row level security;

create policy "exchanges_anon_deny" on "public"."exchanges" for all to anon using (false);
create policy "exchanges_select" on "public"."exchanges" for select to authenticated using (has_exchange_agreements_access());
